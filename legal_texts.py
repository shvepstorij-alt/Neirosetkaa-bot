def document_pages(text):
    """Split at complete paragraphs without cutting Telegram HTML entities."""
    pages=[]
    current=""
    for paragraph in text.strip().split("\n\n"):
        candidate=(current+"\n\n"+paragraph) if current else paragraph
        if len(candidate.encode("utf-16-le"))//2>3500:
            if current:pages.append(current)
            current=paragraph
        else:
            current=candidate
    if current:pages.append(current)
    return pages


