"""Keep legal conclusions separate from current checkout instructions."""
import re


_PAYMENT = re.compile(
    r'опла[тч]|плат[её]ж|покуп|приобр(?:ести|етен|ет)|списан|'
    r'оформ[^.!?\n]{0,20}подписк|подписк[^.!?\n]{0,20}оформ|'
    r'перев(?:од|ести)[^.!?\n]{0,20}(?:деньг|средств)|'
    r'(?:деньг|средств)[^.!?\n]{0,20}перев(?:од|ести)', re.I)
_LEGAL = re.compile(
    r'\bзакон(?:н[а-яё]*|одательств[а-яё]*|а|у|ом|е)?\b|'
    r'легальн|правомерн|\bдопустим(?:а|о|ы)?\s+ли\b|'
    r'(?:разрешен|разрешён|запрещен|запрещён)[а-яё]*\s+ли', re.I)


def reply(text):
    """Return a narrow handoff without asserting a legal conclusion."""
    value = str(text or '')
    if not (_PAYMENT.search(value) and _LEGAL.search(value)):
        return None
    body = (
        'Способ оплаты выбирайте только из вариантов, которые сейчас показывает '
        'бот-магазин для вашего заказа.\n\n'
        'Подтвердить юридическую оценку без актуального проверенного основания '
        'не могу. Этот вопрос уточнит Александр.'
    )
    return {
        'reply': body,
        'summary': ('Клиент задал правовой вопрос об оплате. Юридический вывод и '
                    'актуальный способ оплаты не подтверждены исторической перепиской.'),
        'handoff': True,
        'source_ids': [],
        'evidence': {
            'status': 'clarification',
            'sources': [],
            'owner_action_required': True,
            'diagnostic': ('Этап: правовая оценка способа оплаты. Нарушенное условие: '
                           'нельзя подтверждать законность без актуального проверенного '
                           'основания. Подтверждено только наличие правового вопроса; '
                           'способ оплаты берётся из текущего заказа.'),
        },
    }
