"""Narrow ChatGPT Images guidance for a character from a reference photo."""
import re


SOURCE='https://help.openai.com/en/articles/11084440-images-in-chatgpt'
_BLOCK=r'сколько|цен[аы]|стоим|тариф|план|оплат|куп|оформ|активир|лимит|подпис|гарант|сравн|\bvs\b|модель|регион|vpn|впн|доступ|аккаунт|войти|логин|парол|код|ошиб|блокиров|возврат|ваш\s+бот|в\s+боте|каталог|кредит'


def reply(current):
    text=str(current or '')
    if re.search(_BLOCK,text,re.I):
        return None
    photo=bool(re.search(r'фото|фотограф|изображени|картинк|референс',text,re.I))
    character=bool(re.search(r'персонаж|геро[яй]|аватар|стил[еяиз]',text,re.I))
    creation=bool(re.search(r'созда|сдела|нарис|сгенерир|преврат',text,re.I))
    named=bool(re.search(r'chat\s*gpt|чат\s*гпт|\bgpt\b',text,re.I))
    if not named or not photo or not creation:
        return None
    if re.search(r'чуж[а-яё]*\s+фото|без\s+соглас|документ|паспорт|лиц[а-яё]*\s+другого|'
                 r'фото[^.!?\n]{0,30}(?:друг|подруг|реб[её]н|клиент)|'
                 r'(?:друг|подруг|реб[её]н|клиент)[^.!?\n]{0,30}фото',text,re.I):
        return None
    body=('В ChatGPT Images можно прикрепить фото-референс и описать, какого персонажа или стиль хотите получить. '
          'Например: «сделай персонажа в стиле комикса, сохрани позу и палитру».\n\n'
          'Используйте только своё фото или фото с разрешением человека на обработку. Результат лучше проверить и при необходимости уточнить стиль или детали в следующем сообщении.')
    return {'reply':body,'summary':'Подтверждённая навигация ChatGPT Images для персонажа/стилизации по референс-фото без обещаний сходства, тарифа или лимитов.',
            'handoff':False,'source_ids':[],
            'evidence':{'status':'official_guidance','sources':[SOURCE],
                        'diagnostic':'Этап: создание изображения по референс-фото. Архивная цепочка 891005→891006 подтверждает запрос клиента на персонажа из фото и совет владельца использовать ChatGPT; результата клиент не подтвердил. Официальная справка OpenAI проверена 11.11.2026: ChatGPT Images создаёт изображения и редактирует загруженные фото по описанию. Сходство, тарифы, лимиты и результат не утверждались.'}}
